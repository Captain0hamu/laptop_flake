#!/usr/bin/env node
import { readFileSync, writeFileSync, existsSync, copyFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '..');
const read = path => readFileSync(join(root, path), 'utf8');
// Explicit allowlist: never read local.nix, generated host data, or user files.
const paths = [
  'modules/nixos/bootloader.nix', 'files/grub/keep-menu-on-boot.patch',
  'modules/nixos/plymouth.nix', 'files/plymouth/gtg/gtg.script',
  'modules/nixos/desktop.nix', 'files/sddm/Gently-Blur-SDDM-6/AnimatedBackground.qml',
  'files/sddm/Gently-Blur-SDDM-6/IntroOverlay.qml', 'files/sddm/Gently-Blur-SDDM-6/SplashHud.qml',
  'files/kitty/kitty.conf', 'files/oh-my-posh/distrous-nixos.omp.json',
  'files/fastfetch/config.jsonc',
  'devshells/tor.nix', 'scripts/tor-banner.sh', 'scripts/nixos-functions.sh',
  'files/nvim/init.lua', 'home/neovim.nix', 'modules/nixos/audio.nix',
  'modules/nixos/boot.nix', 'modules/nixos/virtualisation.nix',
  'home/plasma.nix', 'home/easyeffects.nix',
  'modules/nixos/plasma-customisation.nix',
  'files/plasma/SharedScene.qml', 'files/plasma/Splash.qml',
  'files/plasma/patch-lockscreen.py', 'files/plasma/build-translucent-theme.py',
  'files/sddm/Gently-Blur-SDDM-6/Main.qml',
];
const frames = [...read('files/sddm/Gently-Blur-SDDM-6/anim/frames.js').matchAll(/"([^"\n]+\.jpg)"/g)].map(match => match[1]);
for (const frame of frames) {
  if (!existsSync(join(root, 'files/sddm/Gently-Blur-SDDM-6/anim', frame))) throw new Error(`Missing frame: ${frame}`);
}
const qml = read('files/sddm/Gently-Blur-SDDM-6/AnimatedBackground.qml');
const duration = Number(qml.match(/frameDuration:\s*(\d+)/)?.[1]);
if (!duration || !frames.length) throw new Error('Missing animation settings');
if (process.argv.includes('--refresh-previews')) {
  const expression = 'c: { grub = "${c.boot.loader.grub.theme}/background.png"; plymouth = "${builtins.head c.boot.plymouth.themePackages}/share/plymouth/themes/gtg/background.png"; }';
  const assets = JSON.parse(execFileSync('nix', ['eval', '--impure', '--json', '.#nixosConfigurations.nixos.config', '--apply', expression], { cwd: root, encoding: 'utf8' }));
  for (const [name, path] of Object.entries(assets)) {
    if (!existsSync(path)) throw new Error('Build the NixOS system first, then refresh previews.');
    copyFileSync(path, join(directory, 'assets', `${name}-background.png`));
  }
}
const data = { frames, duration, sources: Object.fromEntries(paths.map(path => [path, read(path)])) };
writeFileSync(join(directory, 'showcase-data.js'), `// Generated by generate-showcase.mjs; contains only allowlisted repository sources.\nwindow.NIX_SHOWCASE = ${JSON.stringify(data, null, 2).replace(/</g, '\\u003c')};\n`);
console.log(`Showcase: ${frames.length} frames, ${paths.length} source files.`);
